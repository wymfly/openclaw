import fs from "node:fs/promises";

const root = new URL("../", import.meta.url);
const sourcePath = new URL("source/deck-api.contract.ts", root);
const tsOutPath = new URL("generated/ts/deck-api.generated.ts", root);
const goOutPath = new URL("../backend/internal/deckapi/types.generated.go", root);

const source = await fs.readFile(sourcePath, "utf8");
const tsExpected = `// AUTO-GENERATED FROM contracts/source/deck-api.contract.ts\n// Do not edit this file directly.\n\n${source}`;

function titleCase(name) {
  return name.slice(0, 1).toUpperCase() + name.slice(1);
}

function splitUnion(type) {
  return type
    .split("|")
    .map((part) => part.trim())
    .filter(Boolean);
}

function normalizeType(type) {
  const parts = splitUnion(type);
  const filtered = parts.filter((part) => part !== "null" && part !== "undefined");
  return filtered.join(" | ");
}

function toGoType(type) {
  const normalized = normalizeType(type);
  if (normalized.includes("|")) {
    const parts = splitUnion(normalized);
    if (parts.every((part) => /^".+"$/.test(part))) {
      return "string";
    }
  }
  if (normalized === "string") {
    return "string";
  }
  if (normalized === "boolean") {
    return "bool";
  }
  if (normalized === "number") {
    return "float64";
  }
  if (normalized === "unknown") {
    return "any";
  }
  if (normalized === "Record<string, unknown>") {
    return "map[string]any";
  }
  if (normalized === "Record<string, string>") {
    return "map[string]string";
  }
  if (normalized.startsWith("Array<") && normalized.endsWith(">")) {
    return "[]" + toGoType(normalized.slice(6, -1));
  }
  if (normalized.endsWith("[]")) {
    return "[]" + toGoType(normalized.slice(0, -2));
  }
  return normalized;
}

const interfaceMatches = [...source.matchAll(/export interface (\w+) \{([\s\S]*?)\n\}/g)];
const goBodies = interfaceMatches.map(([, name, body]) => {
  const lines = body
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => line.replace(/,$/, ""));
  const fields = lines.map((line) => {
    const match = line.match(/^(\w+)(\?)?:\s(.+);$/);
    if (!match) {
      throw new Error(`Unable to parse field line: ${line}`);
    }
    const [, fieldName, optionalMark, rawType] = match;
    const goName = titleCase(fieldName);
    const goType = toGoType(rawType.trim());
    const omitEmpty = optionalMark ? ",omitempty" : "";
    return `\t${goName} ${goType} \`json:"${fieldName}${omitEmpty}"\``;
  });
  return `type ${name} struct {\n${fields.join("\n")}\n}`;
});

const goExpected = `// AUTO-GENERATED FROM contracts/source/deck-api.contract.ts\n// Do not edit this file directly.\n\npackage deckapi\n\n${goBodies.join("\n\n")}\n`;

const tsActual = await fs.readFile(tsOutPath, "utf8");
const goActual = await fs.readFile(goOutPath, "utf8");

if (tsActual !== tsExpected) {
  console.error(
    "deck-api.generated.ts is stale. Run: node contracts/scripts/sync-deck-api-generated.mjs",
  );
  process.exit(1);
}
if (goActual !== goExpected) {
  console.error(
    "types.generated.go is stale. Run: node contracts/scripts/sync-deck-api-generated.mjs",
  );
  process.exit(1);
}

console.log("deck-api generated artifacts are up to date");
