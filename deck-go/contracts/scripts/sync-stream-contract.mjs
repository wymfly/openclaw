import fs from "node:fs/promises";

const root = new URL("../", import.meta.url);
const sourcePath = new URL("source/deck-streams.contract.json", root);
const apiContractPath = new URL("source/deck-api.contract.ts", root);
const docPath = new URL("../docs/deck-stream-contract.md", root);

function exportedDeckGoTypes(source) {
  return new Set(
    [...source.matchAll(/export\s+(?:interface|type)\s+(DeckGo[A-Za-z0-9_]+)/g)].map(
      (match) => match[1],
    ),
  );
}

function validateContract(contract, generatedTypes) {
  const issues = [];
  for (const stream of contract.streams ?? []) {
    if (!stream.endpoint || !stream.transport) {
      issues.push(`${stream.endpoint ?? "<missing endpoint>"}: missing endpoint or transport`);
    }
    for (const event of stream.events ?? []) {
      if (!event.event || !event.payload || !event.status || !event.source) {
        issues.push(
          `${stream.endpoint} ${event.event ?? "<missing event>"}: missing required field`,
        );
      }
      if (event.status === "generated-dto" && !generatedTypes.has(event.payload)) {
        issues.push(
          `${event.event}: generated DTO ${event.payload} is not in deck-api.contract.ts`,
        );
      }
    }
  }
  for (const endpoint of contract.controlEndpoints ?? []) {
    for (const field of ["endpoint", "request", "response", "source"]) {
      if (!endpoint[field]) {
        issues.push(`${endpoint.endpoint ?? "<missing endpoint>"}: missing ${field}`);
      }
    }
    if (endpoint.request && !generatedTypes.has(endpoint.request)) {
      issues.push(
        `${endpoint.endpoint}: request DTO ${endpoint.request} is not in deck-api.contract.ts`,
      );
    }
    if (endpoint.response && !generatedTypes.has(endpoint.response)) {
      issues.push(
        `${endpoint.endpoint}: response DTO ${endpoint.response} is not in deck-api.contract.ts`,
      );
    }
  }
  return issues;
}

function renderMarkdown(contract) {
  const lines = [
    "# Deck Go Stream Contract",
    "",
    "Generated by `make stream-contract-sync`.",
    "",
    "This document explicitly contracts Deck Go SSE stream envelopes while stream payload DTO migration is staged.",
    "",
    "## SSE Streams",
    "",
  ];

  for (const stream of contract.streams ?? []) {
    lines.push(`### ${stream.endpoint}`, "", `- Transport: \`${stream.transport}\``);
    lines.push(`- Last-Event-ID: ${stream.lastEventId ? "supported" : "not supported"}`);
    lines.push(`- Heartbeat: ${stream.heartbeat ?? "none"}`);
    if (stream.notes) {
      lines.push(`- Notes: ${stream.notes}`);
    }
    lines.push(
      "",
      "| Event | Payload | Status | Source | Notes |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const event of stream.events ?? []) {
      lines.push(
        `| \`${event.event}\` | \`${event.payload}\` | \`${event.status}\` | \`${event.source}\` | ${event.notes ?? ""} |`,
      );
    }
    lines.push("");
  }

  lines.push(
    "## JSON Stream Control Endpoints",
    "",
    "| Endpoint | Request | Response | Source | Notes |",
    "| --- | --- | --- | --- | --- |",
  );
  for (const endpoint of contract.controlEndpoints ?? []) {
    lines.push(
      `| \`${endpoint.endpoint}\` | \`${endpoint.request}\` | \`${endpoint.response}\` | \`${endpoint.source}\` | ${endpoint.notes ?? ""} |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

async function main() {
  const contract = JSON.parse(await fs.readFile(sourcePath, "utf8"));
  const generatedTypes = exportedDeckGoTypes(await fs.readFile(apiContractPath, "utf8"));
  const issues = validateContract(contract, generatedTypes);
  if (issues.length > 0) {
    for (const issue of issues) {
      console.error(`stream-contract: ${issue}`);
    }
    process.exit(1);
  }

  const expected = renderMarkdown(contract);
  if (process.env.CHECK_MODE === "1") {
    const actual = await fs.readFile(docPath, "utf8");
    if (actual !== expected) {
      console.error(
        "deck-stream-contract.md is stale. Run: node contracts/scripts/sync-stream-contract.mjs",
      );
      process.exit(1);
    }
    console.log("stream contract is up to date");
    return;
  }

  await fs.writeFile(docPath, expected, "utf8");
  console.log(`wrote ${docPath.pathname}`);
}

await main();
